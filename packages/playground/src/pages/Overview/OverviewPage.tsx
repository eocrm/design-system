import type { ReactNode } from 'react';
import { Link as RouterLink } from 'react-router';
import { Stack, Cluster, Grid, Title, Text, Code, Link, LinkCard } from '@eocrm/design-system';
import { CodeBlock } from '../components/CodeBlock';
import {
  componentCatalog,
  componentGroups,
  tokensReference,
  architectureReference,
} from '../../layout/AppShell/navItems';
import styles from './OverviewPage.module.scss';

const REPO_URL = 'https://github.com/eocrm/design-system';
const NPM_URL = 'https://www.npmjs.com/package/@eocrm/design-system';
const DOCS_URL = `${REPO_URL}/tree/main/packages/design-system/docs`;
const README_URL = `${REPO_URL}/blob/main/packages/design-system/README.md`;

const componentCount = componentGroups.reduce((n, g) => n + g.items.length, 0);

const SETUP = `// main.tsx — once, at the app root
import '@eocrm/design-system/styles/global.css';
import { AppProvider } from '@eocrm/design-system';

createRoot(document.getElementById('root')!).render(
  <AppProvider locale="en" intlLocale="en-US">
    <App />
  </AppProvider>,
);`;

const USAGE = `import { Button, Card, Input, Stack } from '@eocrm/design-system';

export function InviteCard() {
  return (
    <Card>
      <Stack gap="md">
        <Input placeholder="name@company.com" aria-label="Email" />
        <Button>Send invite</Button>
      </Stack>
    </Card>
  );
}`;

const THEME = `<!-- Omit data-theme to follow the OS; omit data-accent for blue. -->
<html data-theme="dark" data-accent="tealpine">`;

const REBRAND = `const tokens = useMemo(() => ({ '--color-accent': '#7c3aed' }), []);
const darkTokens = useMemo(() => ({ '--color-accent': '#a78bfa' }), []);

<AppProvider locale="en" tokens={tokens} darkTokens={darkTokens}>
  <App />
</AppProvider>;`;

const NEXT = `// app/providers.tsx — AppProvider must mount from a client file
'use client';
import { AppProvider, ru } from '@eocrm/design-system';

export function Providers({ children }: { children: React.ReactNode }) {
  return (
    <AppProvider locale="ru" messages={ru}>
      {children}
    </AppProvider>
  );
}`;

const VITEST = `// vitest.config.ts — Node can't import the components' .css
test: { server: { deps: { inline: [/@eocrm\\/design-system/] } } },`;

const MCP = `claude mcp add --scope user eocrm-design-system -- npx -y @eocrm/design-system-mcp`;

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section>
      <Stack gap="md">
        <Title order={2}>{title}</Title>
        {children}
      </Stack>
    </section>
  );
}

function QuickLink({
  to,
  href,
  title,
  body,
}: {
  to?: string;
  href?: string;
  title: string;
  body: string;
}) {
  const card = (
    <Stack gap="xs">
      <Text weight="semibold">{title}</Text>
      <Text size="sm" tone="muted">
        {body}
      </Text>
    </Stack>
  );
  return to ? (
    <LinkCard as={RouterLink} to={to}>
      {card}
    </LinkCard>
  ) : (
    <LinkCard href={href} target="_blank" rel="noreferrer">
      {card}
    </LinkCard>
  );
}

